import re

def extract_deadline(text):

    # Pattern: by Friday / by Monday
    match = re.search(r'\bby\s+([A-Za-z]+)', text, re.IGNORECASE)
    if match:
        return match.group(1)

    # Pattern: before Friday / before Monday
    match = re.search(r'\bbefore\s+([A-Za-z]+)', text, re.IGNORECASE)
    if match:
        return match.group(1)

    # Pattern: tomorrow
    if re.search(r'\btomorrow\b', text, re.IGNORECASE):
        return "Tomorrow"

    # Pattern: next Monday / next Friday
    match = re.search(r'\bnext\s+([A-Za-z]+)', text, re.IGNORECASE)
    if match:
        return "Next " + match.group(1)

    return "Not specified"

df["extracted_deadline"] = df["meeting_text"].apply(extract_deadline)

df[["meeting_text", "extracted_deadline"]]

def extract_action(text):

    # Remove deadline part
    text = re.sub(
        r'\b(by|before)\s+[A-Za-z]+',
        '',
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r'\btomorrow\b',
        '',
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r'\bnext\s+[A-Za-z]+',
        '',
        text,
        flags=re.IGNORECASE
    )

    # Remove person's name
    words = text.strip().split()

    if len(words) > 1:
        text = " ".join(words[1:])

    # Remove helping words
    text = re.sub(
        r'\b(will|must|should|need to)\b',
        '',
        text,
        flags=re.IGNORECASE
    )

    # Remove extra spaces and punctuation
    text = re.sub(r'[.]', '', text)
    text = re.sub(r'\s+', ' ', text).strip()

    # Capitalize first letter
    return text.capitalize()

df["extracted_action"] = df["meeting_text"].apply(extract_action)

df[["meeting_text", "extracted_action"]]

def extract_priority(text):

    text = text.lower()

    # High priority words
    if any(word in text for word in [
        "must", "urgent", "critical", "immediately", "asap"
    ]):
        return "High"

    # Medium priority words
    elif any(word in text for word in [
        "should", "need to", "important"
    ]):
        return "Medium"

    # Default
    else:
        return "Low"

df["extracted_priority"] = df["meeting_text"].apply(extract_priority)

