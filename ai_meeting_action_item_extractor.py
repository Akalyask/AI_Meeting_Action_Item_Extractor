def extract_person(text):
    # Take the first word of the sentence
    first_word = text.strip().split()[0]

    # Remove punctuation
    first_word = re.sub(r'[^A-Za-z]', '', first_word)

    # If sentence starts with "The", it is a team task
    if first_word.lower() in ["the", "team"]:
        return "Team"

    return first_word

df["extracted_person"] = df["meeting_text"].apply(extract_person)

